def _json_default(value: object) -> object:
    return asdict(value) if hasattr(value, "__dataclass_fields__") else str(value)


def _delegation_control(host: ConversationHost, command: str) -> None:
    if command == "status":
        print(json.dumps(host.delegation_status(), ensure_ascii=False,
                         default=_json_default), file=sys.stderr)
    elif command in ("on", "off"):
        host.set_automatic_delegation(command == "on")
        print(f"[automatic delegation enabled={host.delegation_status()['enabled']}]",
              file=sys.stderr)
    else:
        raise ValueError("Controls: :delegation on/off/status")


def _context_control(host: ConversationHost, command: str) -> None:
    if command == "status":
        print(json.dumps(host.automatic_status(), ensure_ascii=False,
                         default=_json_default), file=sys.stderr)
        return
    if host.automatic is None:
        raise ValueError("Automatic maintenance requires durable JSON chat.")
    if command == "retry":
        host.automatic.request_retry(host.session.conversation_id)
        print("[maintenance retry allowed on the next eligible pressure observation]",
              file=sys.stderr)
    elif command in ("pause", "resume"):
        host.automatic.set_enabled(command == "resume")
        print(f"[maintenance enabled={host.automatic.enabled}]", file=sys.stderr)
    else:
        raise ValueError("Controls: :context status/pause/resume/retry")


def _background_control(host: ConversationHost, command_line: str) -> None:
    command, _, value = command_line.partition(" ")
    if command == "submit" and value.strip():
        job = host.submit(value)
        print(f"[background job={job.job_id} status={job.status.value}]", file=sys.stderr)
        return
    if command == "unattach" and not value:
        host.unattach()
        print("[background attachment removed]", file=sys.stderr)
        return
    if command not in ("status", "show", "cancel", "attach"):
        raise ValueError("Controls: :bg submit/status/cancel/show/attach/unattach")

    job_id = UUID(value.strip())
    if command == "cancel":
        host.cancel(job_id)
        print("[background cancelled or completed result withdrawn]", file=sys.stderr)
    elif command == "show":
        print("[Background findings generated by a model; unverified]", file=sys.stderr)
        print(json.dumps(asdict(host.show(job_id)), ensure_ascii=False, default=str),
              file=sys.stderr)
    else:
        job = host.attach(job_id) if command == "attach" else host.status(job_id)
        revision = job.request.snapshot.revision if job.request.snapshot else None
        print(
            f"[background job={job.job_id} status={job.status.value} "
            f"source_revision={revision} submitted={job.created_at.isoformat()} "
            f"invalidated={job.invalidated} delivered_turn={job.delivered_turn_id} "
            f"{'attached for next turn' if command == 'attach' else ''}]",
            file=sys.stderr,
        )


def _control(host: ConversationHost, text: str) -> None:
    """Route operational commands without adding them to Akane's transcript."""
    if text == ":retry commit":
        host.retry_commit()
        print("[exchange committed without regeneration]", file=sys.stderr)
    elif text.startswith(":delegation "):
        _delegation_control(host, text.removeprefix(":delegation "))
    elif text.startswith(":context "):
        _context_control(host, text.removeprefix(":context "))
    elif text.startswith(":session "):
        value = text.removeprefix(":session ").strip()
        session = host.switch_session(None if value == "new" else UUID(value))
        print(f"[session={session.conversation_id}]", file=sys.stderr)
    elif text.startswith(":bg "):
        _background_control(host, text.removeprefix(":bg "))
    else:
        raise ValueError("Unknown terminal control command.")


def _background_budgets(decision_protocol: str) -> tuple[BackgroundLimits, AutoDelegationLimits]:
    """One bounded worker budget shared by all terminal chat startup paths."""
    if decision_protocol == "intent-only":
        return (BackgroundLimits(max_output_tokens=384, max_seconds=40.0),
                AutoDelegationLimits(task_tokens=1024, output_tokens=384, seconds=40.0))
    return BackgroundLimits(), AutoDelegationLimits()


def chat(
    model_path: Path, *, context_size: int, max_tokens: int,
    data_dir: Path | None = None, profile_id: UUID | None = None,
    conversation_id: UUID | None = None, automatic_delegation: bool | None = None,
    decision_protocol: str = 'union',
) -> int:
    if (data_dir is None) != (profile_id is None):
        raise ValueError("Persistent chat requires both data directory and profile ID.")
    if conversation_id is not None and data_dir is None:
        raise ValueError("Session resume requires a data directory and profile ID.")
    with ExitStack() as resources:
        store = None
        if data_dir is not None:
            store = resources.enter_context(JSONContinuityStore(data_dir, profile_id))
            session = store.get_session(conversation_id) if conversation_id is not None else store.create_session()
            conversation_id = session.conversation_id
            print(f"[profile={profile_id} session={conversation_id}]", file=sys.stderr)
        else:
            conversation_id = uuid4()
        model = NativeModel(model_path, context_size=context_size)
        resources.callback(model.close)
        interaction = InteractionModel(model, max_tokens=max_tokens,decision_protocol=decision_protocol)
        scheduler = InferenceScheduler()
        resources.callback(scheduler.shutdown)
        scheduler_profile = profile_id if profile_id is not None else uuid4()
        worker_limits, delegation_limits = _background_budgets(decision_protocol)
        executor = NativeBackgroundExecutor(scheduler_profile, model, scheduler, limits=worker_limits)
        if automatic_delegation is None:
            automatic_delegation = bool(delegation_config.DEFAULT_AUTODELEGATION and store is not None
                                        and getattr(model,'supports_decisions',False))
        if automatic_delegation and not getattr(model,'supports_decisions',False):
            raise ValueError('This backend has not advertised structured decision support.')
        host = ConversationHost(scheduler_profile, conversation_id, interaction, scheduler, executor, store=store,
                                automatic_context=AutomaticContextPolicy(segment_exchanges=4) if store is not None else None,
                                automatic_delegation=automatic_delegation, delegation_limits=delegation_limits)
        resources.callback(host.close)
        owner = TurnCancellationOwner()
        active_turn = None

        def interrupt(_signal, _frame):
            if active_turn is not None:
                owner.cancel(active_turn)
                host.cancel_turn(active_turn)
            else:
                raise KeyboardInterrupt

        previous_handler = signal.signal(signal.SIGINT, interrupt)
        resources.callback(signal.signal, signal.SIGINT, previous_handler)
        print(f"[Metal model loaded in {model.load_seconds:.2f}s; Ctrl-C interrupts; /quit exits]", file=sys.stderr)
        while True:
            try:
                text = input("You> ")
            except EOFError:
                return 0
            except KeyboardInterrupt:
                print()
                continue
            if text == "/quit":
                return 0
            if not text.strip():
                continue
            if text.startswith(":bg ") or text.startswith(":session ") or text.startswith(":delegation ") or text in (":retry commit", ":context status", ":context pause", ":context resume", ":context retry"):
                try:
                    _control(host, text)
                except Exception as error:
                    print(f"[control error: {error}]", file=sys.stderr)
                continue
            active_turn = uuid4()
            token = owner.begin(active_turn)
            started = perf_counter()
            stream_started = False
            print("Akane> ", end="", flush=True)
            try:
                with closing(host.stream(text, cancellation=token)) as events:
                    for event in events:
                        if event.kind == "reply_started":
                            stream_started = True
                        elif event.kind == "reply_text_delta":
                            print(event.text, end="", flush=True)
                        elif event.kind == "reply_cancelled":
                            print("\n[cancelled]", file=sys.stderr)
                        elif event.kind == "reply_failed":
                            print(f"\n[error: {event.message}]", file=sys.stderr)
            except GenerationCancelled:
                print("\n[cancelled]", file=sys.stderr)
            except Exception as error:
                print(f"\n[error: {error}]", file=sys.stderr)
            finally:
                owner.finish(active_turn)
                active_turn = None
                print()
            metrics = interaction.last_generation_metrics if stream_started and interaction.last_prompt is not None else None
            if metrics is not None:
                first_visible = (host.delegation_status().get('first_visible_total_seconds')
                                 if host.delegation_status()['enabled'] else metrics.first_text_seconds)
                ttft = f"{first_visible:.3f}s" if first_visible is not None else "n/a"
                rate = metrics.decode_tokens_per_second
                decode = f"{rate:.1f} samples/s" if rate is not None else "n/a"
                print(
                    f"[prompt={metrics.prompt_tokens} sampled={metrics.sampled_tokens} "
                    f"first_text={ttft} turn={perf_counter() - started:.3f}s "
                    f"decode={decode} finish={metrics.finish_reason}]", file=sys.stderr,
                )

            if host.automatic is not None:
                status = host.automatic_status()
                info = status['prompt']
                maintenance = status['maintenance']
                if info is not None:
                    print(f"[context prompt={info.prompt_tokens} memory_tokens={info.memory_tokens} "
                          f"summary={info.summary_used} segments={len(info.included_segments)} "
                          f"omitted_segments={len(info.omitted_segments)} summary_tokens={info.summary_tokens} "
                          f"recent_only_fallback={info.fallback} "
                          f"maintenance={maintenance.state} error={maintenance.error}]", file=sys.stderr)

            if host.delegation_status()['enabled']:
                delegation = host.delegation_status()
                print(f"[delegation state={delegation['state']} l1_passes={len(delegation['passes'])} "
                      f"handoff={delegation.get('handoff','none')}]",file=sys.stderr)
